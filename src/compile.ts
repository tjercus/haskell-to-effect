/**
 * The compiler pipeline: source text → TypeScript module.
 */
import { Result } from "effect";
import { readFileSync } from "node:fs";
import { CodegenError, generate } from "./codegen/ts.ts";
import { lowerModule } from "./core/lower.ts";
import { LexError, ParseError, ScopeError, TypeCheckError } from "./errors.ts";
import { parseModule } from "./syntax/parser.ts";
import type { Span } from "./syntax/span.ts";
import { inferProgram } from "./types/infer.ts";

export type CompileError = LexError | ParseError | ScopeError | TypeCheckError | GenerateError;

/** A program the code generator cannot translate (an unsupported feature). */
export class GenerateError {
  readonly _tag = "GenerateError";
  constructor(
    readonly message: string,
    readonly span: Span,
  ) {}
}

export interface CompileOptions {
  /** Source file name, used in runtime error messages. */
  readonly fileName: string;
  /** Import path of the runtime from the generated module. */
  readonly runtimeImport?: string;
}

export interface Compiled {
  /** The generated TypeScript module. */
  readonly code: string;
}

/** Parses, checks and compiles a Haskell module. */
export const compile = (
  source: string,
  options: CompileOptions,
): Result.Result<Compiled, CompileError> => {
  const parsed = parseModule(source);
  if (Result.isFailure(parsed)) return Result.fail(parsed.failure);
  const lowered = lowerModule(parsed.success);
  if (Result.isFailure(lowered)) return Result.fail(lowered.failure);
  const typed = inferProgram(lowered.success);
  if (Result.isFailure(typed)) return Result.fail(typed.failure);
  try {
    const code = generate(typed.success, {
      fileName: options.fileName,
      runtimeImport: options.runtimeImport ?? "./hs-runtime.ts",
    });
    return Result.succeed({ code });
  } catch (e) {
    if (e instanceof CodegenError) return Result.fail(new GenerateError(e.message, e.span));
    throw e;
  }
};

/** Source of the runtime module, which is copied next to every generated module. */
export const runtimeSource = (): string =>
  readFileSync(new URL("./runtime/hs-runtime.ts", import.meta.url), "utf8");

/** Entry point that runs a compiled module's `main`. */
export const entrySource = (moduleFile: string, prog: string): string =>
  [
    `// Generated by haskell-to-effect. Runs ${moduleFile}.`,
    `import { runModule } from "./hs-runtime.ts";`,
    `await runModule(() => import(${JSON.stringify(`./${moduleFile}`)}), ${JSON.stringify(prog)});`,
    "",
  ].join("\n");

/** Formats a compile error as `file:line:col: error: message` with the offending source line. */
export const formatError = (e: CompileError, source: string, fileName: string): string => {
  const { start, end } = e.span;
  if (start.line === 0) return `${fileName}: error: ${e.message}`;
  const line = source.split(/\r\n|\r|\n/)[start.line - 1] ?? "";
  const width =
    end.line === start.line
      ? Math.max(1, end.col - start.col)
      : Math.max(1, line.length - start.col + 1);
  const gutter = String(start.line).length;
  return [
    `${fileName}:${start.line}:${start.col}: error: ${e.message}`,
    `${" ".repeat(gutter)} |`,
    `${start.line} | ${line}`,
    `${" ".repeat(gutter)} | ${" ".repeat(start.col - 1)}${"^".repeat(width)}`,
  ].join("\n");
};

export { LexError, ParseError, ScopeError, TypeCheckError };
